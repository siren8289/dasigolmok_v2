def wait_ready(timeout: int = 60) -> bool:
    import time

    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with connect() as conn:
                conn.execute("SELECT 1")
            return True
        except Exception:
            time.sleep(1)
    return False


def restart_postgres() -> str:
    subprocess.run(["docker", "restart", CONTAINER], check=True, timeout=90)
    if not wait_ready(90):
        raise RuntimeError("재시작 후 127.0.0.1:55432 접속 실패")
    proc = subprocess.run(
        ["docker", "logs", "--since", "90s", CONTAINER],
        capture_output=True,
        text=True,
        timeout=30,
    )
    return (proc.stdout or "") + (proc.stderr or "")


def psql(sql: str, dbname: str = "dasigolmok") -> subprocess.CompletedProcess:
    return subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "psql", "-v", "ON_ERROR_STOP=1", "-U", "dasi", "-d", dbname],
        input=sql.encode(),
        capture_output=True,
        timeout=180,
    )


def reset_database() -> None:
    with connect("postgres") as conn:
        conn.execute(
            """
            SELECT pg_terminate_backend(pid)
            FROM pg_stat_activity
            WHERE datname IN ('dasigolmok', 'qa_v9_partial')
              AND pid <> pg_backend_pid()
            """
        )
        conn.execute("DROP DATABASE IF EXISTS qa_v9_partial")
        conn.execute("DROP DATABASE IF EXISTS dasigolmok")
        conn.execute("CREATE DATABASE dasigolmok OWNER dasi")


def apply_migrations() -> list[dict]:
    logs = []
    for path in sorted(MIGRATION_DIR.glob("V*.sql")):
        proc = psql(path.read_text(encoding="utf-8"))
        err = proc.stderr.decode(errors="replace")
        logs.append({"file": path.name, "code": proc.returncode, "stderr": err[-1500:]})
        if proc.returncode != 0:
            break
    return logs


def explanation_length() -> int:
    match = re.search(r"@Column\(length\s*=\s*(\d+)\)\s*\n\s*private String explanation;", read(ENTITY))
    if not match:
        raise AssertionError("explanation @Column(length) 를 찾지 못했다")
    return int(match.group(1))


