def migrations_ok() -> bool:
    logs = STATE.get("migrations") or []
    return len(logs) == 9 and all(item["code"] == 0 for item in logs)


def require_schema(request) -> None:
    if not migrations_ok():
        failed = next((item for item in STATE.get("migrations", []) if item["code"] != 0), None)
        detail = failed["file"] + " " + failed["stderr"][-400:] if failed else "마이그레이션 로그 없음"
        fail(request, "선행 V1~V9 적용이 끝나지 않아 이 조건을 확인할 수 없다. " + detail)


def try_sql(sql: str, params=None, dbname: str = "dasigolmok"):
    with connect(dbname) as conn:
        try:
            conn.execute(sql, params or ())
        except psycopg.Error as exc:
            primary = exc.diag.message_primary if exc.diag else str(exc)
            return f"{exc.sqlstate} {primary}"
    return None


def one(sql: str, params=None, dbname: str = "dasigolmok"):
    with connect(dbname) as conn:
        return conn.execute(sql, params or ()).fetchone()


def vec(n: int, value: str = "0.1") -> str:
    return "[" + ",".join([value] * n) + "]"


