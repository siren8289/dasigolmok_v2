def test_DB03_016(request):
    require_schema(request)
    checks = connect_fetch(
        """
        SELECT pg_get_constraintdef(oid) FROM pg_constraint
        WHERE conrelid='support_policies'::regclass AND contype='c'
        """
    )
    err = try_sql(
        """
        INSERT INTO support_policies
            (id, title, organization, start_date, end_date, description)
        VALUES ('qa-date-order', '역전기간', '기관', '2026-12-31', '2026-01-01', '종료가 시작보다 이름')
        """
    )
    if checks or err is not None:
        ev(request, f"CHECK={checks} insert_err={err}")
        if err is None:
            fail(request, f"CHECK가 있는데 역전 날짜가 저장됐다. {checks}")
        return
    fail(
        request,
        "support_policies에 end_date>=start_date CHECK가 없다. start_date='2026-12-31', end_date='2026-01-01' INSERT가 성공했다. "
        "날짜 검증 제약이 필요하다.",
    )


