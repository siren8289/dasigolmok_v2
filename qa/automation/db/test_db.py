def test_DB01_016(request):
    errors: list[str] = []
    ids: list[int] = []
    lock = threading.Lock()

    def work(index: int) -> None:
        try:
            with connect() as conn:
                rid = conn.execute(
                    "INSERT INTO diagnosis (district, danger) VALUES (%s, false) RETURNING id",
                    (f"concurrent-{index}",),
                ).fetchone()[0]
            with lock:
                ids.append(rid)
        except Exception as exc:
            with lock:
                errors.append(str(exc))

    threads = [threading.Thread(target=work, args=(index,)) for index in range(20)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    if errors or len(ids) != 20 or len(set(ids)) != 20:
        fail(request, f"동시 20건 실패 errors={errors[:3]} ids={len(ids)} unique={len(set(ids))}")
    ev(request, f"스레드 20개가 동시에 INSERT 했고 id {len(set(ids))}개가 모두 다르다. 범위 {min(ids)}–{max(ids)}.")


